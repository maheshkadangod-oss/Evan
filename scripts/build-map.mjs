// Generates src/us-map.js: a US outline (Albers USA) plus projected client locations.
// Run with `node scripts/build-map.mjs` when the location list changes.
import { readFileSync, writeFileSync } from 'node:fs'
import { feature, mesh } from 'topojson-client'
import { presimplify, simplify, quantile } from 'topojson-simplify'
import { geoAlbersUsa, geoPath } from 'd3-geo'

const raw = JSON.parse(readFileSync(new URL('../node_modules/us-atlas/states-10m.json', import.meta.url)))
const pre = presimplify(raw)
const topo = simplify(pre, quantile(pre, 0.12))
const W = 960, H = 600
const projection = geoAlbersUsa().scale(1280).translate([W / 2, H / 2])
const path = geoPath(projection)
const nation = path(feature(topo, topo.objects.nation))
const states = path(mesh(topo, topo.objects.states, (a, b) => a !== b))
const round = (d) => d.replace(/(\d+)\.\d+/g, '$1')

// city, [lon, lat], client names from the case study deck
const places = [
  { city: 'Naples, FL', at: [-81.795, 26.142], hq: true, clients: ['Naples Urgent Care'] },
  { city: 'New York, NY', at: [-74.006, 40.713], clients: ['Dello Russo Laser Vision', 'I Love Kickboxing'] },
  { city: 'Bradley, IL', at: [-87.861, 41.141], clients: ['Peddinghaus'] },
  { city: 'Nashville, TN', at: [-86.781, 36.163], clients: ['Nashville Grading & Drainage', 'TN Pool Builders'] },
  { city: 'New Orleans, LA', at: [-90.072, 29.951], clients: ['New Orleans Native Tours'] },
].map((p) => ({ ...p, xy: projection(p.at).map((v) => Math.round(v * 10) / 10) }))

writeFileSync(new URL('../src/us-map.js', import.meta.url),
  `// Generated by scripts/build-map.mjs. Do not edit by hand.\n` +
  `export const mapSize = ${JSON.stringify({ w: W, h: H })}\n` +
  `export const nationPath = ${JSON.stringify(round(nation))}\n` +
  `export const statesPath = ${JSON.stringify(round(states))}\n` +
  `export const places = ${JSON.stringify(places, null, 2)}\n`)
console.log('ok', places.map((p) => p.city + ' ' + p.xy).join(' | '))
